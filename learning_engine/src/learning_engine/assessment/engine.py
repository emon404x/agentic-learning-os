"""Advanced Assessment Engine (Feature Set G).

Generates and evaluates:
- Multiple-choice questions (mcq)
- Short-answer questions (short_answer)
- Long-answer questions (long_answer)
- Programming problems (coding)
- Mathematical worked problems (math)
- Scenario-based questions (scenario)
- Practical examinations (practical)
- Viva simulations (viva)
- Timed mock tests (mock_exam)

Never claims that an AI-generated score is an official examination grade.
"""

from __future__ import annotations

from typing import Any
from ..core.models import AssessmentItem

FORMATIVE_DISCLAIMER = (
    "Formative Assessment Notice: Scores and feedback generated by Stardi AI are diagnostic study aids "
    "to help you identify knowledge gaps and are never an official academic or certification grade."
)


def generate_exam_suite(
    topic: str,
    concept_id: str = "core-concept",
    difficulty: str = "intermediate",
    duration_minutes: int = 45,
) -> dict[str, Any]:
    """Generate a comprehensive exam preparation & mock test suite across all question types."""
    items: list[AssessmentItem] = [
        AssessmentItem(
            question_id=f"{concept_id}-mcq-1",
            concept_id=concept_id,
            question_type="mcq",
            prompt=f"Which statement best describes the primary invariant of {topic}?",
            difficulty=difficulty,
            options=[
                f"A) {topic} guarantees consistency by enforcing explicit structural constraints before state transitions.",
                f"B) {topic} bypasses validation to maximize raw throughput in all scenarios.",
                f"C) {topic} only applies to stateless single-threaded workloads.",
                f"D) {topic} eliminates the need for error handling or boundary checks.",
            ],
            correct_answer="A",
            rubric=["Selects option A", "Identifies constraint enforcement before state transition"],
            explanation=f"Option A is correct because {topic} relies on preserving invariants across state changes.",
            points=10,
        ),
        AssessmentItem(
            question_id=f"{concept_id}-short-1",
            concept_id=concept_id,
            question_type="short_answer",
            prompt=f"Define {topic} in 2–3 sentences and state one real-world failure mode when it is misconfigured.",
            difficulty=difficulty,
            correct_answer=f"{topic} defines a deterministic protocol/structure for managing state and resources; misconfiguration leads to inconsistency, contention, or data loss.",
            rubric=["Clear definition", "Concrete failure mode", "Accurate technical terminology"],
            explanation="Short exam answers should pair a concise formal definition with a concrete operational consequence.",
            points=15,
        ),
        AssessmentItem(
            question_id=f"{concept_id}-math-1",
            concept_id=concept_id,
            question_type="math",
            prompt=f"Worked Analytical Problem ({topic}): Given a workload of N = 1,000 operations where 80% hit a fast path (cost = 2 ms) and 20% trigger a fallback path (cost = 25 ms), calculate the expected average latency per operation.",
            difficulty=difficulty,
            correct_answer="6.6 ms",
            rubric=[
                "Sets up weighted expectation formula: E[T] = p_hit * T_hit + p_miss * T_miss",
                "Computes 0.80 * 2 ms = 1.6 ms and 0.20 * 25 ms = 5.0 ms",
                "Sums 1.6 + 5.0 = 6.6 ms with units",
            ],
            worked_solution_steps=[
                "Step 1: Write the expected latency equation: E[T] = P(fast) * T_fast + P(fallback) * T_fallback.",
                "Step 2: Substitute values: E[T] = (0.80 * 2 ms) + (0.20 * 25 ms).",
                "Step 3: Compute terms: 1.6 ms + 5.0 ms = 6.6 ms per operation.",
            ],
            explanation="Weighted expectation problems appear frequently in OS, networking, architecture, and database exams.",
            points=20,
        ),
        AssessmentItem(
            question_id=f"{concept_id}-long-1",
            concept_id=concept_id,
            question_type="long_answer",
            prompt=f"Compare the primary competing approaches within {topic}, analyzing their time/space overhead, consistency guarantees, and when an engineer should choose one over the other.",
            difficulty=difficulty,
            correct_answer="A thorough answer compares at least two approaches across overhead, guarantees, and workload trade-offs.",
            rubric=["Architecture/mechanism comparison", "Time & space trade-offs", "Failure/consistency analysis", "Clear decision criterion"],
            explanation="Long-answer questions test synthesis and trade-off reasoning rather than isolated recall.",
            points=25,
        ),
        AssessmentItem(
            question_id=f"{concept_id}-scenario-1",
            concept_id=concept_id,
            question_type="scenario",
            prompt=f"Production Scenario ({topic}): Latency spikes 10x under concurrent load while CPU usage remains below 20%. Diagnose the most likely bottleneck related to {topic} and propose a verifiable remediation.",
            difficulty=difficulty,
            correct_answer="Low CPU with high latency under concurrency points to lock contention, I/O blocking, or queue saturation.",
            rubric=["Diagnoses contention/blocking vs CPU bound", "Proposes instrumentation step", "Describes concrete remediation"],
            explanation="Low CPU + high latency is the classic signature of waiting on locks, I/O, or network timeouts.",
            points=15,
        ),
        AssessmentItem(
            question_id=f"{concept_id}-viva-1",
            concept_id=concept_id,
            question_type="viva",
            prompt=f"Viva / Oral Defense Question: If an examiner asks 'Why not always use the strictest setting in {topic}?', how do you defend the engineering trade-off?",
            difficulty=difficulty,
            correct_answer="Strictest guarantees incur coordination/serialization overhead that reduces throughput or availability.",
            rubric=["Identifies overhead of strict guarantees", "Gives a concrete example of acceptable relaxation"],
            explanation="In viva examinations, examiners probe whether you understand the cost of guarantees.",
            points=15,
        ),
    ]

    return {
        "topic": topic,
        "concept_id": concept_id,
        "difficulty": difficulty,
        "timed_mock_duration_minutes": duration_minutes,
        "total_points": sum(i.points for i in items),
        "disclaimer": FORMATIVE_DISCLAIMER,
        "items": [i.to_dict() for i in items],
    }


def evaluate_submission(
    item: AssessmentItem | dict[str, Any],
    learner_answer: str,
) -> dict[str, Any]:
    """Evaluate a submitted answer across 6 criteria with explicit uncertainty & revision advice."""
    data = item.to_dict() if isinstance(item, AssessmentItem) else item
    qtype = data.get("question_type", "short_answer")
    max_pts = int(data.get("points", 10))
    ans = learner_answer.strip()
    correct_ref = str(data.get("correct_answer", "")).strip()
    rubric = data.get("rubric", [])

    if not ans:
        return {
            "question_id": data.get("question_id", ""),
            "score": 0,
            "max_score": max_pts,
            "percentage": 0.0,
            "criteria_breakdown": {
                "correctness": 0.0,
                "conceptual_understanding": 0.0,
                "completeness": 0.0,
                "reasoning": 0.0,
                "terminology": 0.0,
                "practical_implementation": 0.0,
            },
            "correct_answer": correct_ref,
            "explanation": data.get("explanation", ""),
            "mistakes": ["Blank submission."],
            "improvement_recommendations": [f"Review foundational lesson for `{data.get('concept_id', 'topic')}`."],
            "recommended_revision_lessons": [data.get("concept_id", "core-concept")],
            "grading_uncertainty": "Low (empty response).",
            "disclaimer": FORMATIVE_DISCLAIMER,
        }

    if qtype == "mcq":
        chosen = ans[0].upper()
        expected = correct_ref[0].upper() if correct_ref else "A"
        is_right = chosen == expected
        score = max_pts if is_right else 0
        ratio = 1.0 if is_right else 0.0
        uncertainty = "Deterministic (objective multiple-choice key)."
        mistakes = [] if is_right else [f"Selected `{chosen}`, whereas the verified answer is `{expected}`."]
    else:
        # Multi-criteria rubric evaluation for analytical/subjective answers
        tokens = {t.lower().strip(".,;:!?()") for t in correct_ref.split() if len(t) > 3}
        rubric_tokens = {t.lower().strip(".,;:!?()") for r in rubric for t in r.split() if len(t) > 3}
        all_targets = tokens | rubric_tokens
        ans_lower = ans.lower()
        hits = sum(1 for t in all_targets if t in ans_lower) if all_targets else 1
        coverage = min(1.0, hits / max(1, len(all_targets) * 0.5))
        length_factor = min(1.0, len(ans.split()) / 12.0)
        ratio = round(0.65 * coverage + 0.35 * length_factor, 2)
        score = int(round(max_pts * ratio))
        uncertainty = (
            "Moderate (subjective/open-ended response evaluated via rubric keyword and structure coverage; "
            "human instructor grading may weight phrasing differently)."
        )
        mistakes = [] if ratio >= 0.75 else ["Partial rubric coverage or missing step-by-step justification."]

    return {
        "question_id": data.get("question_id", ""),
        "concept_id": data.get("concept_id", "core-concept"),
        "score": score,
        "max_score": max_pts,
        "percentage": round(ratio * 100, 1),
        "criteria_breakdown": {
            "correctness": round(ratio, 2),
            "conceptual_understanding": round(ratio, 2),
            "completeness": round(min(1.0, len(ans.split()) / 15.0) if qtype != "mcq" else ratio, 2),
            "reasoning": round(ratio, 2),
            "terminology": round(ratio, 2),
            "practical_implementation": round(ratio, 2),
        },
        "correct_answer": correct_ref,
        "explanation": data.get("explanation", ""),
        "mistakes": mistakes,
        "improvement_recommendations": (
            ["Solid work! Proceed to the next module or spaced-repetition check."]
            if ratio >= 0.8
            else [
                f"Re-read the worked solution steps for `{data.get('concept_id', 'topic')}`.",
                "Practice explaining the trade-off and boundary conditions aloud.",
            ]
        ),
        "recommended_revision_lessons": [] if ratio >= 0.8 else [data.get("concept_id", "core-concept")],
        "grading_uncertainty": uncertainty,
        "disclaimer": FORMATIVE_DISCLAIMER,
    }
